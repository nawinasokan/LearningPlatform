-- SQL Sandbox schema initialization (deterministic seed data; safe to re-run on a fresh container)
-- Creates a separate `sandbox` schema with internally consistent datasets for the SQL Lab:
--   employees   : departments, employees (manager hierarchy, ties, NULL dept, inactive staff), employee_salary_history
--   orders      : customers, products, orders, order_items (order totals == sum of items)
--   banking     : accounts, transactions (accounts.balance == credits - debits)
--   activity    : logins (gaps and islands), contact_imports (duplicate rows)
--   learning    : students, courses, enrollments (relational division)
-- All names/e-mails are fictitious and use example domains.

CREATE DATABASE interview_sandbox;

\c interview_sandbox;

CREATE SCHEMA IF NOT EXISTS sandbox;

-- ─── Employees Dataset ─────────────────────────────────────────────
CREATE TABLE sandbox.departments (
    id SERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    location VARCHAR(100),
    budget NUMERIC(12,2)
);

CREATE TABLE sandbox.employees (
    id SERIAL PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    department_id INT REFERENCES sandbox.departments(id),
    salary NUMERIC(10,2) NOT NULL,
    hire_date DATE NOT NULL,
    job_title VARCHAR(100),
    manager_id INT REFERENCES sandbox.employees(id),
    is_active BOOLEAN DEFAULT TRUE
);

CREATE TABLE sandbox.employee_salary_history (
    id SERIAL PRIMARY KEY,
    employee_id INT NOT NULL REFERENCES sandbox.employees(id),
    salary NUMERIC(10,2) NOT NULL,
    effective_date DATE NOT NULL
);

-- ─── Orders Dataset ────────────────────────────────────────────────
CREATE TABLE sandbox.customers (
    id SERIAL PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(100) UNIQUE,
    city VARCHAR(100),
    country VARCHAR(100),
    created_at TIMESTAMP DEFAULT NOW()
);

CREATE TABLE sandbox.products (
    id SERIAL PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    category VARCHAR(100),
    price NUMERIC(10,2) NOT NULL,
    stock_quantity INT DEFAULT 0
);

CREATE TABLE sandbox.orders (
    id SERIAL PRIMARY KEY,
    customer_id INT REFERENCES sandbox.customers(id),
    order_date TIMESTAMP DEFAULT NOW(),
    total_amount NUMERIC(12,2) NOT NULL,
    status VARCHAR(50) DEFAULT 'pending',
    shipping_city VARCHAR(100)
);

CREATE TABLE sandbox.order_items (
    id SERIAL PRIMARY KEY,
    order_id INT REFERENCES sandbox.orders(id),
    product_id INT REFERENCES sandbox.products(id),
    quantity INT NOT NULL,
    unit_price NUMERIC(10,2) NOT NULL
);

-- ─── Banking Dataset ───────────────────────────────────────────────
CREATE TABLE sandbox.accounts (
    id SERIAL PRIMARY KEY,
    customer_name VARCHAR(100) NOT NULL,
    account_type VARCHAR(50) NOT NULL,
    balance NUMERIC(14,2) DEFAULT 0.00,
    created_at TIMESTAMP DEFAULT NOW()
);

CREATE TABLE sandbox.transactions (
    id SERIAL PRIMARY KEY,
    account_id INT REFERENCES sandbox.accounts(id),
    transaction_type VARCHAR(50) NOT NULL,   -- 'credit' or 'debit'
    amount NUMERIC(12,2) NOT NULL,           -- always positive
    description VARCHAR(255),
    transaction_date TIMESTAMP DEFAULT NOW()
);

-- ─── Activity Dataset ──────────────────────────────────────────────
CREATE TABLE sandbox.logins (
    id SERIAL PRIMARY KEY,
    user_id INT NOT NULL,
    login_date DATE NOT NULL
);

CREATE TABLE sandbox.contact_imports (
    id SERIAL PRIMARY KEY,
    email VARCHAR(100) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    source VARCHAR(50) NOT NULL,
    imported_at TIMESTAMP NOT NULL
);

-- ─── Learning Dataset ──────────────────────────────────────────────
CREATE TABLE sandbox.students (
    id SERIAL PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL
);

CREATE TABLE sandbox.courses (
    id SERIAL PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    credits INT NOT NULL
);

CREATE TABLE sandbox.enrollments (
    id SERIAL PRIMARY KEY,
    student_id INT NOT NULL REFERENCES sandbox.students(id),
    course_id INT NOT NULL REFERENCES sandbox.courses(id),
    enrolled_on DATE NOT NULL,
    score INT,            -- NULL while the course is still in progress
    UNIQUE (student_id, course_id)
);


